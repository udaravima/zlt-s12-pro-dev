#!/usr/bin/env python3
"""Extract the Le9641 VP-API-II profiles from stock Tozed firmware.

    extract_profiles.py <mislic-binary | stock mtd4 firmware dump> [out.c]

Optional since slic-fxs r5: the build needs only slicctl/board_profile.c
(the device profile, committed). Use this to check that file against your
own stock dump, or to build in Tozed's DC-feed/ring set ("B", SLIC_DC=B /
SLIC_RING=B).

The stock `mislic` daemon embeds Profile Wizard byte arrays. Each starts with
a 4-byte header: 0x0D (VP886/887 family), profile type, index, length-4,
followed by a format-version byte. Types: 0xFF device, 0x01 DC feed,
0x02 tone, 0x04 ringing.

Tozed's own set sits next to the device profile in .rodata ("B"); copies of
the same types further away are labelled "A" (likely API defaults).

A full mtd4 dump has a partly corrupt squashfs on this board, so we don't
unsquash it: we decode every xz stream independently and pick the block
that holds mislic.
"""
import lzma
import re
import sys

TYPES = {0xFF: 'DEV', 0x01: 'DC', 0x02: 'TONE', 0x04: 'RING', 0x00: 'AC'}
MARK = b'Device PCN not recognized in ZL880 or miSLIC families'


def find_mislic(data):
    if data[:4] == b'\x7fELF':
        return data
    i = data.find(b'\xfd7zXZ\x00')
    while i != -1:
        try:
            out = lzma.LZMADecompressor(format=lzma.FORMAT_XZ).decompress(
                data[i:i + 2_000_000], max_length=4_000_000)
            if MARK in out and out[:4] == b'\x7fELF':
                return out
        except lzma.LZMAError:
            pass
        i = data.find(b'\xfd7zXZ\x00', i + 6)
    sys.exit('mislic not found in input')


def profiles(b):
    found = []
    for m in re.finditer(rb'\x0d([\x00\x01\x02\x04\xff])\x00', b):
        i, ptype, ln = m.start(), b[m.start() + 1], b[m.start() + 3]
        if 4 <= ln <= 0x60 and 1 <= b[i + 4] <= 15:
            found.append((i, ptype, b[i:i + 4 + ln]))
    return found


def main():
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else 'stock_profiles.c'
    b = find_mislic(open(src, 'rb').read())
    ps = profiles(b)
    devs = [p for p in ps if p[1] == 0xFF]
    if len(devs) != 1:
        sys.exit(f'expected one device profile, found {len(devs)}')
    dev_off = devs[0][0]
    lines = ['/* Generated by fxs/tools/extract_profiles.py from stock Tozed mislic.',
             ' * Do not commit: Tozed firmware data. */',
             '#include "vp_api_types.h"', '']
    for ptype in (0xFF, 0x01, 0x02, 0x04):
        group = sorted((p for p in ps if p[1] == ptype), key=lambda p: abs(p[0] - dev_off))
        for rank, (off, _, blob) in enumerate(group[:2]):
            if ptype == 0xFF:
                name = 'STOCK_DEV_PROFILE'
            elif ptype == 0x02:
                if rank:
                    continue
                name = 'STOCK_TONE_PROFILE'
            else:
                name = f'STOCK_{TYPES[ptype]}_PROFILE_{"B" if rank == 0 else "A"}'
            lines.append(f'/* offset 0x{off:x}, type 0x{ptype:02x}, version {blob[4]}, {len(blob)} bytes */')
            lines.append(f'const VpProfileDataType {name}[] = {{')
            for j in range(0, len(blob), 12):
                lines.append('    ' + ', '.join(f'0x{x:02X}' for x in blob[j:j + 12]) + ',')
            lines += ['};', '']
    open(out, 'w').write('\n'.join(lines))
    print(f'wrote {out}: device profile at 0x{dev_off:x}, {len(ps)} profiles seen')


if __name__ == '__main__':
    main()
