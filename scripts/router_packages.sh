#!/bin/sh
# Runs ON THE ROUTER (OpenWrt 25.x, apk v3, BusyBox ash).
#
# The package half of rebuilding the router after a factory reset: which
# packages were added on top of the firmware image, and putting them back.
#
#   snapshot   print the added packages (stdout), one per line, with a header:
#     /usr/bin/ssh root@<router> 'sh -s -- snapshot' < scripts/router_packages.sh > scripts/router-packages.txt
#   check      compare the router with a list: what's missing, what's extra (read-only)
#   restore    install what's missing from the list (refuses without extroot)
#     L=$(grep -v '^#' scripts/router-packages.txt | tr '\n' ' ')
#     /usr/bin/ssh root@<router> "sh -s -- check $L"   < scripts/router_packages.sh
#     /usr/bin/ssh root@<router> "sh -s -- restore $L" < scripts/router_packages.sh
#
# "Added" = in /etc/apk/world (what was asked for explicitly) but not in the
# firmware's own /rom/etc/apk/world. Dependencies are never listed: apk pulls
# them in again. Locally built packages (world pins them by checksum,
# "name><Q1...") can't come from a feed; snapshot lists them as "# local:"
# comment lines, and they are installed from fxs/build (doc 15 step 5).
#
# restore needs extroot first (router_extroot.sh): the internal flash has
# about 4 MiB writable, and the packages here take about 250 MiB.

mode=${1:-}
[ $# -gt 0 ] && shift

die() { echo "router_packages: $*" >&2; exit 1; }
# package names from a world file, without version/pin constraints
names() { sed 's/[<>=~].*//' "$1" 2>/dev/null | grep . | sort -u; }
# installed names, including names a package *provides*: world may ask for
# "hostapd" and get it from a differently named package that provides it
installed() {
	awk '/^P:/ { print substr($0, 3) }
	     /^p:/ { n = split(substr($0, 3), a, " "); for (i = 1; i <= n; i++) { sub(/[<>=~].*/, "", a[i]); print a[i] } }' \
		/lib/apk/db/installed | sort -u
}
added() { # in world, not in the firmware's world, not locally built
	names /rom/etc/apk/world >"$T/rom"
	names /etc/apk/world | grep -vxF -f "$T/rom" | grep -vxF -f "$T/pins"
}
local_pins() { grep '><' /etc/apk/world | sed 's/[<>=~].*//' | sort -u; }
T=/tmp/router_packages.$$
mkdir -p "$T" || exit 1
trap 'rm -rf "$T"' EXIT
local_pins >"$T/pins"

on_extroot() {
	set -- $(awk '$2 == "/overlay" { d = $1; t = $3 } END { print d, t }' /proc/mounts)
	case $1:$2 in /dev/sd*:ext4 | /dev/sd*:f2fs | /dev/mmcblk*:ext4 | /dev/mmcblk*:f2fs) return 0 ;; esac
	return 1
}

case $mode in
snapshot)
	. /etc/openwrt_release
	echo "# Packages added on top of the firmware image ($(date +%Y-%m-%d), $DISTRIB_RELEASE $DISTRIB_REVISION, $DISTRIB_ARCH)."
	echo "# Generated by router_packages.sh snapshot; restore with router_packages.sh restore."
	echo "# Dependencies are not listed (apk adds them). Lines starting with # are ignored."
	for p in $(local_pins); do echo "# local: $p   (fxs/build, apk add --allow-untrusted)"; done
	names /etc/apk/world >"$T/world"
	gone=$(names /rom/etc/apk/world | grep -vxF -f "$T/world")
	[ -n "$gone" ] && echo "# removed from the image's set (restore doesn't remove these): $(echo $gone)"
	added
	;;
check | restore)
	[ $# -gt 0 ] || die "give the package list as arguments (see the header)"
	installed >"$T/inst"
	missing=$(for p in "$@"; do grep -qxF "$p" "$T/inst" || echo "$p"; done)
	printf '%s\n' "$@" | sort -u >"$T/want"
	extra=$(added | grep -vxF -f "$T/want")
	echo "list: $# packages; missing on the router: $(echo $missing | wc -w)"
	[ -n "$missing" ] && echo "  missing: $(echo $missing)"
	if [ "$mode" = check ]; then
		[ -n "$extra" ] && echo "  extra (added on the router, not in the list): $(echo $extra)"
		[ -z "$missing" ]
		exit
	fi
	[ -n "$missing" ] || { echo "nothing to install"; exit 0; }
	on_extroot || die "/overlay is not on extroot (internal flash: ~4 MiB). Run router_extroot.sh attach first."
	free=$(df -k /overlay | awk 'NR == 2 { print int($4 / 1024) }')
	[ "$free" -ge 500 ] || die "only $free MiB free on /overlay; need ~500"
	apk update >/dev/null || die "apk update failed: is the WAN up?"
	# one transaction first (apk resolves everything at once); if a single name
	# is unknown apk refuses the lot, so then go one by one and report
	# shellcheck disable=SC2086
	if apk add $missing; then
		echo "installed $(echo $missing | wc -w) package(s)"
	else
		failed=""
		for p in $missing; do apk add "$p" >/dev/null 2>&1 || failed="$failed $p"; done
		[ -n "$failed" ] && die "could not install:$failed (renamed or dropped from the feed?)"
	fi
	echo "next: locally built packages, then slic-asterisk-setup (doc 15)"
	;;
*)
	echo "usage: sh -s -- snapshot | check PKG... | restore PKG...   (see the header)" >&2
	exit 2
	;;
esac
